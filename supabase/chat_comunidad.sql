create table if not exists public.plan_intereses (
  plan_id bigint not null references public.planes_sociales(id) on delete cascade,
  client_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (plan_id, client_id)
);

alter table public.plan_intereses enable row level security;

create or replace function public.registrar_interes_plan(p_plan_id bigint, p_client_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
  v_capacity integer;
  v_status text;
begin
  select interesados_count, cupo, estado
    into v_count, v_capacity, v_status
  from public.planes_sociales
  where id = p_plan_id
  for update;

  if not found or v_status <> 'aprobado' then
    raise exception 'PLAN_UNAVAILABLE';
  end if;

  if exists (
    select 1 from public.plan_intereses
    where plan_id = p_plan_id and client_id = p_client_id
  ) then
    return v_count;
  end if;

  if v_capacity is not null and v_count >= v_capacity then
    raise exception 'PLAN_FULL';
  end if;

  insert into public.plan_intereses (plan_id, client_id)
  values (p_plan_id, p_client_id);

  update public.planes_sociales
  set interesados_count = interesados_count + 1
  where id = p_plan_id
  returning interesados_count into v_count;

  return v_count;
end;
$$;

revoke all on function public.registrar_interes_plan(bigint, uuid) from public;
grant execute on function public.registrar_interes_plan(bigint, uuid) to anon, authenticated;

create table if not exists public.chat_mensajes (
  id bigint generated by default as identity primary key,
  ciudad text not null check (ciudad in (
    'Valencia', 'Madrid', 'Barcelona', 'Málaga', 'Alicante', 'Sevilla'
  )),
  apodo text not null check (char_length(apodo) between 2 and 30),
  mensaje text not null check (char_length(mensaje) between 2 and 280),
  plan_id bigint references public.planes_sociales(id) on delete set null,
  estado text not null default 'visible' check (estado in ('visible', 'oculto')),
  created_at timestamptz not null default now()
);

create index if not exists chat_mensajes_ciudad_fecha_idx
  on public.chat_mensajes (ciudad, created_at desc)
  where estado = 'visible';

alter table public.chat_mensajes enable row level security;

drop policy if exists "Mensajes visibles son publicos" on public.chat_mensajes;
create policy "Mensajes visibles son publicos"
  on public.chat_mensajes for select
  to anon, authenticated
  using (estado = 'visible' and created_at >= now() - interval '15 days');

drop policy if exists "Administradores leen todos los mensajes" on public.chat_mensajes;
create policy "Administradores leen todos los mensajes"
  on public.chat_mensajes for select
  to authenticated
  using (true);

drop policy if exists "Administradores moderan mensajes" on public.chat_mensajes;
create policy "Administradores moderan mensajes"
  on public.chat_mensajes for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "Administradores eliminan mensajes" on public.chat_mensajes;
create policy "Administradores eliminan mensajes"
  on public.chat_mensajes for delete
  to authenticated
  using (true);

create table if not exists public.chat_rate_limits (
  client_id uuid primary key,
  last_sent_at timestamptz not null default '2000-01-01',
  window_started_at timestamptz not null default now(),
  messages_in_window integer not null default 0
);

alter table public.chat_rate_limits enable row level security;

create table if not exists public.chat_reportes (
  id bigint generated by default as identity primary key,
  mensaje_id bigint not null references public.chat_mensajes(id) on delete cascade,
  motivo text not null check (motivo in (
    'spam', 'acoso', 'estafa', 'datos-personales', 'otro'
  )),
  comentario text check (comentario is null or char_length(comentario) <= 300),
  estado text not null default 'pendiente' check (estado in ('pendiente', 'revisado')),
  created_at timestamptz not null default now()
);

create index if not exists chat_reportes_estado_fecha_idx
  on public.chat_reportes (estado, created_at desc);

alter table public.chat_reportes enable row level security;

drop policy if exists "Administradores leen reportes de chat" on public.chat_reportes;
create policy "Administradores leen reportes de chat"
  on public.chat_reportes for select
  to authenticated
  using (true);

drop policy if exists "Administradores revisan reportes de chat" on public.chat_reportes;
