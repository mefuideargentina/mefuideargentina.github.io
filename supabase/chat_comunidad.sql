create or replace function public.publicar_mensaje_chat(
  p_client_id uuid,
  p_ciudad text,
  p_apodo text,
  p_mensaje text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rate public.chat_rate_limits%rowtype;
  v_message_id bigint;
  v_nickname text := trim(p_apodo);
  v_message text := trim(p_mensaje);
begin
  if p_ciudad not in ('Valencia', 'Madrid', 'Barcelona', 'Málaga', 'Alicante', 'Sevilla') then
    raise exception 'INVALID_CITY';
  end if;
  if char_length(v_nickname) not between 2 and 30 then
    raise exception 'INVALID_NICKNAME';
  end if;
  if char_length(v_message) not between 2 and 280 then
    raise exception 'INVALID_MESSAGE';
  end if;
  if v_message ~* '(https?://|www\.|t\.me/|bit\.ly/|tinyurl\.)' then
    raise exception 'LINKS_NOT_ALLOWED';
  end if;

  insert into public.chat_rate_limits (client_id)
  values (p_client_id)
  on conflict (client_id) do nothing;

  select * into v_rate
  from public.chat_rate_limits
  where client_id = p_client_id
  for update;

  if v_rate.last_sent_at > now() - interval '7 seconds' then
    raise exception 'RATE_LIMIT';
  end if;

  if v_rate.window_started_at < now() - interval '1 hour' then
    v_rate.window_started_at := now();
    v_rate.messages_in_window := 0;
  end if;

  if v_rate.messages_in_window >= 30 then
    raise exception 'HOURLY_LIMIT';
  end if;

  if exists (
    select 1 from public.chat_mensajes
    where ciudad = p_ciudad
      and lower(apodo) = lower(v_nickname)
      and lower(mensaje) = lower(v_message)
      and created_at > now() - interval '2 minutes'
  ) then
    raise exception 'DUPLICATE_MESSAGE';
  end if;

  insert into public.chat_mensajes (ciudad, apodo, mensaje)
  values (p_ciudad, v_nickname, v_message)
  returning id into v_message_id;

  update public.chat_rate_limits
  set last_sent_at = now(),
      window_started_at = v_rate.window_started_at,
      messages_in_window = v_rate.messages_in_window + 1
  where client_id = p_client_id;

  delete from public.chat_mensajes
  where created_at < now() - interval '15 days';

  return v_message_id;
end;
$$;

revoke all on function public.publicar_mensaje_chat(uuid, text, text, text) from public;
grant execute on function public.publicar_mensaje_chat(uuid, text, text, text) to anon, authenticated;

create or replace function public.reportar_mensaje_chat(
  p_mensaje_id bigint,
  p_motivo text,
  p_comentario text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_report_id bigint;
begin
  if p_motivo not in ('spam', 'acoso', 'estafa', 'datos-personales', 'otro') then
    raise exception 'INVALID_REASON';
  end if;
  if p_comentario is not null and char_length(trim(p_comentario)) > 300 then
    raise exception 'COMMENT_TOO_LONG';
  end if;
  if not exists (
    select 1 from public.chat_mensajes
    where id = p_mensaje_id and estado = 'visible'
  ) then
    raise exception 'MESSAGE_NOT_FOUND';
  end if;

  insert into public.chat_reportes (mensaje_id, motivo, comentario)
  values (p_mensaje_id, p_motivo, nullif(trim(p_comentario), ''))
  returning id into v_report_id;

  return v_report_id;
end;
$$;

revoke all on function public.reportar_mensaje_chat(bigint, text, text) from public;
grant execute on function public.reportar_mensaje_chat(bigint, text, text) to anon, authenticated;

